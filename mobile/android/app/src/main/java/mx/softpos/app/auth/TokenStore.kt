package mx.softpos.app.auth

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import mx.softpos.app.core.network.KernoJson
import java.util.Base64
import javax.crypto.Cipher
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Session persisted on the device. */
@Serializable
data class StoredSession(
    @SerialName("access_token") val accessToken: String,
    @SerialName("refresh_token") val refreshToken: String,
    @SerialName("access_expires_at_ms") val accessExpiresAtMs: Long,
    @SerialName("user_id") val userId: String = "",
    @SerialName("merchant_id") val merchantId: String = "",
    @SerialName("role") val role: String = "",
    /** Merchants this user can switch to (picker); empty in sessions saved before AND-34. */
    @SerialName("memberships") val memberships: List<MembershipInfo> = emptyList()
) {
    override fun toString(): String = "StoredSession(user=$userId, merchant=$merchantId, role=$role)"
}

fun TokenPair.toStoredSession(nowMs: Long): StoredSession = StoredSession(
    accessToken = accessToken,
    refreshToken = refreshToken,
    accessExpiresAtMs = nowMs + expiresInSeconds * 1000L,
    userId = userId,
    merchantId = merchantId,
    role = role,
    memberships = memberships
)

interface TokenStore {
    fun load(): StoredSession?
    fun save(session: StoredSession)
    fun clear()
}

class InMemoryTokenStore(private var session: StoredSession? = null) : TokenStore {
    @Synchronized override fun load(): StoredSession? = session
    @Synchronized override fun save(session: StoredSession) { this.session = session }
    @Synchronized override fun clear() { session = null }
}

/** Minimal string key-value persistence (SharedPreferences on Android). */
interface KeyValueStore {
    fun getString(key: String): String?
    fun putString(key: String, value: String)
    fun remove(key: String)
}

/** Authenticated encryption of small secrets. */
interface SecretCipher {
    fun encrypt(plaintext: ByteArray): ByteArray
    fun decrypt(ciphertext: ByteArray): ByteArray
}

/**
 * AES-256-GCM with a 128-bit tag. Output = 12-byte IV || ciphertext+tag. The
 * IV is generated by the provider (required by AndroidKeyStore keys, which
 * refuse caller-supplied IVs), so the same class serves Keystore and JVM keys.
 */
class AesGcmSecretCipher(private val keyProvider: () -> SecretKey) : SecretCipher {
    override fun encrypt(plaintext: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, keyProvider())
        val iv = cipher.iv
        require(iv.size == IV_BYTES) { "unexpected GCM IV size ${iv.size}" }
        return iv + cipher.doFinal(plaintext)
    }

    override fun decrypt(ciphertext: ByteArray): ByteArray {
        require(ciphertext.size > IV_BYTES) { "ciphertext too short" }
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(
            Cipher.DECRYPT_MODE,
            keyProvider(),
            GCMParameterSpec(TAG_BITS, ciphertext, 0, IV_BYTES)
        )
        return cipher.doFinal(ciphertext, IV_BYTES, ciphertext.size - IV_BYTES)
    }

    companion object {
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val IV_BYTES = 12
        const val TAG_BITS = 128
    }
}

/**
 * [TokenStore] that keeps the session only as AES-GCM ciphertext (Base64) in
 * a [KeyValueStore]. Plaintext buffers are zeroed in `finally`. A blob that
 * no longer decrypts (key invalidated, tampering) is dropped: the user logs in
 * again instead of crashing.
 */
class EncryptedTokenStore(
    private val kv: KeyValueStore,
    private val cipher: SecretCipher
) : TokenStore {

    @Synchronized
    override fun load(): StoredSession? {
        val encoded = kv.getString(KEY) ?: return null
        var plaintext: ByteArray? = null
        return try {
            plaintext = cipher.decrypt(Base64.getDecoder().decode(encoded))
            KernoJson.decodeFromString(StoredSession.serializer(), plaintext.decodeToString())
        } catch (_: Exception) {
            kv.remove(KEY)
            null
        } finally {
            plaintext?.fill(0)
        }
    }

    @Synchronized
    override fun save(session: StoredSession) {
        val plaintext = KernoJson.encodeToString(StoredSession.serializer(), session).encodeToByteArray()
        try {
            kv.putString(KEY, Base64.getEncoder().encodeToString(cipher.encrypt(plaintext)))
        } finally {
            plaintext.fill(0)
        }
    }

    @Synchronized
    override fun clear() = kv.remove(KEY)

    companion object {
        const val KEY = "session.v1"
    }
}
